import { buildPolicy, CspAllowlist, DEFAULT_REFERRER_POLICY, nonceEnvVar } from './allowlist';

/** First line of every file `pstack csp` writes; files without it are hand-written. */
export const GENERATED_MARKER = '# Generated by pstack csp from csp-allowlist.json';

/** What the release build (secure: true) writes where the nonce goes by default. */
export const CSP_NONCE_SSI = '<!--#echo var="CSP_NONCE" -->';

/**
 * The placeholder the release build must write for this allowlist: the default one, or with
 * nonce-source "env:NAME" an SSI echo of NAME in single quotes (so an unprocessed placeholder
 * cannot end the double-quoted attribute around it).
 */
export function noncePlaceholder(a: CspAllowlist): string {
  const env = nonceEnvVar(a);
  return env ? `<!--#echo var='${env}' -->` : CSP_NONCE_SSI;
}

/** Times "@" is replaced in Apache's UNIQUE_ID (27 characters, so more is vanishingly rare). */
const AT_REPLACEMENTS = 8;

/** A header value inside double quotes in either config (only `"` needs escaping; validated). */
const quoted = (v: string) => v.replace(/"/g, '\\"');

const SECURITY_HEADERS = (a: CspAllowlist): [string, string][] => [
  ['X-Frame-Options', 'SAMEORIGIN'],
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', a.referrerPolicy ?? DEFAULT_REFERRER_POLICY],
  ['Strict-Transport-Security', 'max-age=31536000; includeSubDomains'],
  ['Permissions-Policy', a.permissionsPolicy],
];

const header = (app: string) =>
  `${GENERATED_MARKER} — edit it and run \`pstack csp --app=${app}\`.`;

/**
 * Apache: SPA routing relative to this folder (works under any base href), a per-request nonce
 * filled into index.html by SSI and used in the CSP header, the security headers, and a long
 * cache for hashed files. The nonce is UNIQUE_ID with "@" replaced (mod_unique_id, the default),
 * or with nonce-source "env:NAME" a variable the server sets itself (e.g. mod_lua), used as is.
 */
export function renderHtaccess(app: string, a: CspAllowlist): string {
  const env = nonceEnvVar(a);
  const placeholder = noncePlaceholder(a);
  const policy = buildPolicy(a).replace(/\{N\}/g, env ? `%{${env}}e` : '%{CSP_NONCE}e');
  const includes = a.ssi === 'html' ? 'Includes' : 'IncludesNOEXEC';
  const modules = env
    ? 'mod_rewrite, mod_headers and mod_include'
    : 'mod_rewrite, mod_headers, mod_include, mod_unique_id and mod_setenvif';
  const nonce = env
    ? [
        `# Per-request CSP nonce: ${env}, set by the server for every request (e.g. by mod_lua in a`,
        '# fixups hook), used as is in the header and by SSI.',
      ]
    : [
        '# Per-request CSP nonce: UNIQUE_ID without "@" (not allowed in a nonce). reqenv() reads the',
        '# environment only, so request headers cannot set it.',
        `SetEnvIfExpr "reqenv('UNIQUE_ID') =~ /^(.+)$/" CSP_NONCE=$1`,
        ...Array.from(
          { length: AT_REPLACEMENTS },
          () => `SetEnvIfExpr "reqenv('CSP_NONCE') =~ /^([^@]*)@(.*)$/" CSP_NONCE=$1_$2`,
        ),
      ];
  const ssi =
    a.ssi === 'html'
      ? [
          `# .html files: the release build (secure: true) leaves ${placeholder} where the nonce goes.`,
          'Options +Includes',
          'AddOutputFilter INCLUDES .html',
          '<Files "index.html">',
          '    Header always set Cache-Control "no-store"',
          '</Files>',
        ]
      : [
          `# index.html: the release build (secure: true) leaves ${placeholder} where the nonce goes.`,
          'Options +IncludesNOEXEC',
          '<Files "index.html">',
          '    SetOutputFilter INCLUDES',
          '    Header always set Cache-Control "no-store"',
          '</Files>',
        ];
  const lines = [
    header(app),
    `# Needs ${modules}, and`,
    `# AllowOverride FileInfo Options=${includes} (or All) for this folder.`,
    ...(env ? [`# The server must set ${env} for every request.`] : []),
    '',
    '# Single-page app: anything that is not a file, a folder or a hashed build file gets index.html.',
    'RewriteEngine On',
    'RewriteCond %{REQUEST_FILENAME} !-f',
    'RewriteCond %{REQUEST_FILENAME} !-d',
    'RewriteCond %{REQUEST_URI} !\\.[0-9a-f]{8,}\\.(js|css)$',
    'RewriteRule ^ index.html [L]',
    '',
    ...nonce,
    '',
    ...ssi,
    '',
    '# Security headers',
    // Both tables: "always" alone does not remove a header set without it (or by a backend).
    ...(a.unsetHeaders ?? []).flatMap((h) => [`Header unset ${h}`, `Header always unset ${h}`]),
    ...SECURITY_HEADERS(a).map(([k, v]) => `Header always set ${k} "${quoted(v)}"`),
    `Header always set Content-Security-Policy "${policy}"`,
    ...(a.extraHeaders?.length
      ? [
          '',
          '# extra-headers from csp-allowlist.json, as written',
          ...a.extraHeaders.map(([k, v]) => `Header always set ${k} "${v}"`),
        ]
      : []),
    '',
    '# Long-lived cache for content-hashed files',
    '<FilesMatch "\\.[0-9a-f]{8,}\\.(js|css)$">',
    '    Header set Cache-Control "public, max-age=31536000, immutable"',
    '</FilesMatch>',
    '',
  ];
  return lines.join('\n');
}

/**
 * Nginx: SPA routing, the nonce from $request_id substituted into HTML and used in the CSP
 * header, the security headers in every location (add_header is not inherited once a location
 * sets one), index.html not cached, hashed files cached long.
 */
export function renderNginx(app: string, a: CspAllowlist): string {
  const policy = buildPolicy(a).replace(/\{N\}/g, '$request_id');
  const placeholder = noncePlaceholder(a);
  const q = placeholder.includes("'") ? '"' : "'";
  const headers = (indent: string, extra: [string, string, boolean][] = []) =>
    [
      ...SECURITY_HEADERS(a).map(([k, v]) => [k, v, true] as [string, string, boolean]),
      ['Content-Security-Policy', policy, true] as [string, string, boolean],
      ...extra,
    ]
      .map(([k, v, always]) => `${indent}add_header ${k} "${quoted(v)}"${always ? ' always' : ''};`)
      .join('\n');
  return [
    header(app),
    '# Serve the app at "/"; under a base href (e.g. /portal/) change root/location to match.',
    '',
    'server {',
    '    listen 80;',
    '    server_name _;',
    '    root /usr/share/nginx/html;',
    '    index index.html;',
    '',
    `    # Per-request CSP nonce: the release build (secure: true) leaves ${placeholder}`,
    '    # where the nonce goes.',
    '    sub_filter_once off;',
    `    sub_filter ${q}${placeholder}${q} $request_id;`,
    ...(a.extraHeaders?.length || a.unsetHeaders?.length
      ? ['    # (extra-headers and unset-headers in csp-allowlist.json are for Apache only.)']
      : []),
    '',
    '    location / {',
    '        try_files $uri $uri/ /index.html;',
    headers('        '),
    '    }',
    '',
    '    location = /index.html {',
    headers('        ', [['Cache-Control', 'no-store', true]]),
    '    }',
    '',
    '    # Long-lived cache for content-hashed files',
    '    # (quoted: a regex holding braces must be)',
    '    location ~* "\\.[0-9a-f]{8,}\\.(js|css)$" {',
    '        # Without "always": a 404 for a file not yet uploaded must not be cached for a year.',
    headers('        ', [['Cache-Control', 'public, max-age=31536000, immutable', false]]),
    '    }',
    '}',
    '',
  ].join('\n');
}

/** First line of the Flutter web .htaccess `pstack app` writes (pstack never rewrites it). */
export const FLUTTER_HTACCESS_MARKER = '# Written by pstack app for a Flutter web build';

/**
 * Apache config for a Flutter web build, the counterpart of its server/nginx.conf: SPA routing,
 * the wasm MIME type, security headers and a CSP for the CanvasKit renderer, no-cache for the
 * bootstrap files Flutter does not hash. One per env (environments/<app>/htaccess.<env>).
 */
export function renderFlutterHtaccess(app: string, env: string): string {
  return [
    `${FLUTTER_HTACCESS_MARKER} — ${app}, ${env}. Edit it freely; pstack does not rewrite it.`,
    '# Needs mod_rewrite and mod_headers, and AllowOverride FileInfo (or All) for this folder.',
    '',
    '# Single-page app: anything that is not a file or a folder gets index.html.',
    'RewriteEngine On',
    'RewriteCond %{REQUEST_FILENAME} !-f',
    'RewriteCond %{REQUEST_FILENAME} !-d',
    'RewriteRule ^ index.html [L]',
    '',
    '# WebAssembly (CanvasKit renderer)',
    'AddType application/wasm .wasm',
    '',
    '# Security headers. CanvasKit needs wasm-unsafe-eval and blob: workers; test before tightening.',
    'Header always set X-Frame-Options "SAMEORIGIN"',
    'Header always set X-Content-Type-Options "nosniff"',
    `Header always set Referrer-Policy "${DEFAULT_REFERRER_POLICY}"`,
    'Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"',
    "Header always set Content-Security-Policy \"default-src 'self'; script-src 'self' 'wasm-unsafe-eval' blob:; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'; worker-src blob:; frame-ancestors 'none'\"",
    '',
    '# Flutter does not hash these: always revalidate them.',
    '<FilesMatch "^(index\\.html|flutter_bootstrap\\.js|flutter_service_worker\\.js|version\\.json|manifest\\.json)$">',
    '    Header set Cache-Control "no-cache"',
    '</FilesMatch>',
    '',
  ].join('\n');
}
