function isLeaf(node: unknown): node is { value: TokenValue; comment?: string } {
  return typeof node === 'object' && node !== null && 'value' in node;
}

function deepMerge(target: TokenTree, source: TokenTree): TokenTree {
  for (const [key, node] of Object.entries(source)) {
    const existing = target[key];
    if (!isLeaf(node) && existing && !isLeaf(existing)) {
      deepMerge(existing, node);
    } else {
      target[key] = isLeaf(node) ? { ...node } : deepMerge({}, node);
    }
  }
  return target;
}

/** dictionary.allTokens: the source files deep-merged in name order, then flattened in key order. */
export function flattenTokens(files: Record<string, TokenTree>): FlatToken[] {
  const merged: TokenTree = {};
  for (const name of Object.keys(files).sort()) deepMerge(merged, files[name]);
  const out: FlatToken[] = [];
  const walk = (node: TokenTree, path: string[]) => {
    for (const [key, child] of Object.entries(node)) {
      if (isLeaf(child))
        out.push({ path: [...path, key], value: child.value, comment: child.comment });
      else walk(child, [...path, key]);
    }
  };
  walk(merged, []);
  return out;
}

// lodash-style word splitting, as used by SD's name/cti/* transforms (the template has no digits).
const words = (path: string[]): string[] =>
  path.flatMap((p) => p.split(/[^A-Za-z0-9]+|(?<=[a-z])(?=[A-Z])/)).filter(Boolean);
const lower = (w: string) => w.toLowerCase();
const upperFirst = (w: string) => w.charAt(0).toUpperCase() + w.slice(1);
export const kebabName = (path: string[]) => words(path).map(lower).join('-');
export const camelName = (path: string[]) =>
  words(path)
    .map(lower)
    .map((w, i) => (i === 0 ? w : upperFirst(w)))
    .join('');
export const pascalName = (path: string[]) => upperFirst(camelName(path));

const category = (t: FlatToken) => t.path[0];

/** size/rem */
function sizeRem(t: FlatToken): TokenValue {
  if (category(t) !== 'size') return t.value;
  const n = parseFloat(String(t.value));
  return n === 0 ? '0' : `${n}rem`;
}

/** color/css and color/hex: #rrggbb (the template only has opaque 6-digit colors). */
function colorHex(t: FlatToken): TokenValue {
  return category(t) === 'color' ? String(t.value).toLowerCase() : t.value;
}

/** color/hex8flutter, size/flutter/remToDouble (16px base), font/flutter/literal. */
function flutterValue(t: FlatToken): TokenValue {
  if (category(t) === 'font') return `"${t.value}"`;
  if (category(t) === 'color') {
    return `Color(0xFF${String(t.value).slice(1).toUpperCase()})`;
  }
  if (category(t) === 'size') return (parseFloat(String(t.value)) * 16).toFixed(2);
  return t.value;
}

const withComment = (line: string, t: FlatToken, style: 'short' | 'long' = 'short') =>
  t.comment ? `${line} ${style === 'short' ? `// ${t.comment}` : `/* ${t.comment} */`}` : line;

function longHeader(lines: string[]): string {
  return `/**\n${lines.map((l) => ` * ${l}`).join('\n')}\n */\n\n`;
}

function shortHeader(lines: string[]): string {
  return `\n${lines.map((l) => `// ${l}`).join('\n')}\n\n`;
}

/** scss/variables (transformGroup scss). */
export function renderScss(tokens: FlatToken[]): string {
  const vars = tokens.map((t) =>
    withComment(`$${kebabName(t.path)}: ${colorHex({ ...t, value: sizeRem(t) })};`, t),
  );
  return `${shortHeader(TOKENS_FILE_HEADER)}${vars.join('\n')}\n`;
}

/** css/variables (transformGroup css). */
export function renderCss(tokens: FlatToken[]): string {
  const vars = tokens.map((t) =>
    withComment(`  --${kebabName(t.path)}: ${colorHex({ ...t, value: sizeRem(t) })};`, t, 'long'),
  );
  return `${longHeader(TOKENS_FILE_HEADER)}:root {\n${vars.join('\n')}\n}\n`;
}

/** javascript/es6 (transformGroup js). */
export function renderEs6(tokens: FlatToken[]): string {
  const lines = tokens.map((t) =>
    withComment(
      `export const ${pascalName(t.path)} = ${JSON.stringify(
        colorHex({ ...t, value: sizeRem(t) }),
      )};`,
      t,
    ),
  );
  return `${longHeader(TOKENS_FILE_HEADER)}${lines.join('\n')}\n`;
}

/** flutter/class.dart (transformGroup flutter). */
export function renderDart(tokens: FlatToken[], className: string, destination: string): string {
  // flutter/class.dart sorts tokens by name (code-unit order), unlike the other formats.
  const sorted = [...tokens].sort((a, b) => {
    const x = camelName(a.path);
    const y = camelName(b.path);
    return x < y ? -1 : x > y ? 1 : 0;
  });
  const props = sorted.map((t) =>
    withComment(`static const ${camelName(t.path)} = ${flutterValue(t)};`, t),
  );
  return (
    `\n//\n// ${destination}\n//\n` +
    `${shortHeader(TOKENS_FILE_HEADER)}\n\n` +
    `import 'dart:ui';\n\n` +
    `class ${className} {\n  ${className}._();\n\n    ${props.join('\n    ')}\n}\n`
  );
}
