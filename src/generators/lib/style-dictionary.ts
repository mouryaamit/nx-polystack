/**
 * Renders the outputs Style Dictionary 3 builds from the design-tokens template, so a new lib
 * works before its first `nx build`. Mirrors the SD 3.9 transform groups (scss, css, js, flutter)
 * and formats (scss/variables, css/variables, javascript/es6, flutter/class.dart) for the token
 * shapes the template uses: hex colors, `size` tokens in rem, and plain strings/numbers.
 */

export type TokenValue = string | number;
export interface TokenTree {
  [key: string]: TokenTree | { value: TokenValue; comment?: string };
}

export interface FlatToken {
  /** CTI path, e.g. ['color', 'brand', 'primary'] */
  path: string[];
  value: TokenValue;
  comment?: string;
}

