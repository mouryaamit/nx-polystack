import { majorOf } from '../../lib/utils/dependencies';

import { MIN_CONFIDENCE } from './adapters';

import type {
  Detection,
  IonicReport,
  MigrationReportData,
  WorkspaceReportData,
} from './adapters/types';
import type { ImportRewriteResult, RewriteKind } from './imports/rewrite';
import { ProjectKind, unsupportedReason } from './nx/workspace-source';

export interface ReportInput {
  name: string;
  adapterId: string;
  adapterLabel: string;
  detection: Detection;
  /** Chosen with --adapter. */
  forced: boolean;
  /** Single-app imports: the app folder (default apps/<name>). */
  projectRoot?: string;
  /** --min-confidence, when given. */
  minConfidence?: number;
  /** --source as given on the command line. */
  source: string;
  data: MigrationReportData;
}

const code = (s: string) => `\`${s.replace(/`/g, "'")}\``;

function list(items: string[], empty: string): string {
  return items.length === 0 ? empty : items.map((i) => `- ${i}`).join('\n');
}

/**
 * docs/migrations/<name>.md. Deterministic: no timestamps, sorted lists, so re-running the
 * same migration gives the same file.
 */
export function renderReport(r: ReportInput): string {
  const d = r.data;
  const ws = 'projects' in d ? (d as WorkspaceReportData) : undefined;
  const out: string[] = [];
  out.push(`# Migration report: ${r.name}`);
  out.push(
    `Generated by \`pstack migrate\` (nx-polystack :migrate). The source was copied, not moved; ` +
      'it was not modified.',
  );

  out.push('## Summary');
  out.push(
    [
      `- Source: ${code(r.source)}`,
      `- Adapter: ${code(r.adapterId)} (${r.adapterLabel})`,
      `- Confidence: ${r.detection.confidence.toFixed(2)}${
        r.forced
          ? ' (selected with `--adapter`)'
          : r.minConfidence !== undefined && r.detection.confidence < MIN_CONFIDENCE
          ? ` (accepted with --min-confidence=${r.minConfidence})`
          : ''
      }`,
      `- Detection: ${r.detection.reasons.join('; ')}`,
      ws
        ? `- Projects: ${ws.projects.length} migrated, ${ws.unsupported.length} not supported`
        : `- App: ${code(r.name)} in ${code(r.projectRoot ?? `apps/${r.name}`)}`,
      `- Files copied: ${d.copied}`,
      `- Paths skipped: ${d.skipped.length}`,
      `- Possible secrets not copied: ${d.secrets.length}`,
      `- File list: ${
        d.gitListed
          ? 'git (tracked, and untracked but not ignored, files only)'
          : d.gitignoreUsed
          ? 'all files except those the source .gitignore files ignore (not a git work tree)'
          : 'all files (not a git work tree, no .gitignore)'
      }`,
    ].join('\n'),
  );

  if (ws) {
    out.push('## Projects');
    out.push(
      (ws.layout === 'apps-libs'
        ? 'Apps were copied to `apps/<name>` and libraries to `libs/<name>`. Import aliases keep ' +
          'their names and point at the new folders (library aliases at the library source); ' +
          'source files are unchanged.\n\n'
        : 'Copied to the same paths; project names, import aliases and source files are ' +
          'unchanged (except for `--prefix` renames and the project.json/ESLint updates).\n\n') +
        table(
          ['Project', 'Kind', 'Root', 'Why'],
          ws.projects.map((p) => [
            p.name === p.sourceName
              ? code(p.name)
              : `${code(p.name)} (source: ${code(p.sourceName)})`,
            p.kind,
            code(p.root),
            p.why,
          ]),
        ),
    );
    out.push('## Not migrated');
    out.push(
      ws.unsupported.length === 0
        ? 'None.'
        : 'Kinds nx-polystack cannot migrate yet:\n\n' +
            table(
              ['Project', 'Kind', 'Root', 'Why'],
              ws.unsupported.map((u) => [
                code(u.name),
                u.kind,
                code(u.root),
                unsupportedReason(u.kind as ProjectKind) ?? 'not supported yet',
              ]),
            ),
    );
  }

  if (d.secrets.length > 0) {
    out.push('## Not copied: possible secrets');
    out.push(
      'Environment files, signing keys, credentials and service configs are never copied. Add ' +
        'what the app needs by hand, outside version control where it belongs.\n\n' +
        list([...d.secrets].sort().map(code), 'None.'),
    );
  }

  out.push('## Skipped paths');
  out.push(
    'Not copied (directories end with `/`; build output, caches, VCS data, and workspace-level ' +
      'files that the migration rewrites into the workspace instead).\n\n' +
      list([...d.skipped].sort().map(code), 'None.'),
  );

  if (d.npmProject) {
    out.push('## Dependencies');
    out.push(
      'Source dependencies are added to the root `package.json` only when missing; existing ' +
        'versions are never changed.\n\n' +
        `Added (${d.dependenciesAdded.length}):\n\n` +
        list([...d.dependenciesAdded].sort().map(code), 'None.') +
        '\n\nVersion clashes (the workspace version was kept):\n\n' +
        (d.dependencyClashes.length === 0
          ? 'None.'
          : table(
              ['Package', 'Workspace', 'Source'],
              [...d.dependencyClashes]
                .sort((a, b) => (a.name < b.name ? -1 : 1))
                .map((c) => [code(c.name), code(c.workspace), code(c.source)]),
            )),
    );
  }

  if (d.angularNotes.length > 0) {
    out.push('## Angular version');
    out.push(list(d.angularNotes, 'None.'));
  }

  if (d.npmProject) {
    out.push('## TypeScript path aliases');
    out.push(
      `Added to \`tsconfig.base.json\`: ${
        d.tsPathsAdded.length ? [...d.tsPathsAdded].sort().map(code).join(', ') : 'none'
      }.\n\n` +
        'Clashes (the workspace mapping was kept):\n\n' +
        (d.tsPathClashes.length === 0
          ? 'None.'
          : table(
              ['Alias', 'Workspace', 'Source'],
              [...d.tsPathClashes]
                .sort((a, b) => (a.alias < b.alias ? -1 : 1))
                .map((c) => [
                  code(c.alias),
                  c.workspace.map(code).join(', '),
                  c.source.map(code).join(', '),
                ]),
            )),
    );

    if (d.packageFields.length > 0) {
      out.push('## Other package.json fields');
      out.push(
        d.packageFields
          .map(
            (f) =>
              `- ${code(f.field)} (${f.handling}): ${f.entries
                .map(([k, v]) => `${code(k)}: ${code(v)}`)
                .join(', ')}`,
          )
          .join('\n'),
      );
    }

    out.push('## Source scripts not carried over');
    const scripts = Object.entries(d.sourceScripts).sort(([a], [b]) => (a < b ? -1 : 1));
    out.push(
      scripts.length === 0
        ? 'None.'
        : 'Use the root `package.json` scripts and Nx targets instead. The source had:\n\n' +
            list(
              scripts.map(([k, v]) => `${code(k)}: ${code(v)}`),
              'None.',
            ),
    );
  }

  if (d.imports) {
    out.push('## Imports');
    out.push(importsBlock(d.imports));
  }

  if (d.ionic && d.ionic.length > 0) {
    out.push('## Ionic');
    for (const i of d.ionic) out.push(ionicBlock(i));
  }

  if (d.notes.length > 0) {
    out.push('## Check by hand');
    out.push(list(d.notes, 'None.'));
  }

  out.push('## Next steps');
  out.push(
    [
      '- [ ] `npm install`',
      ...d.nextSteps.map((s) => `- [ ] ${s}`),
      '- [ ] Remove the old repo when you are happy with the migrated app',
      `- [ ] Undo this migration: \`pstack migrate --rollback=${r.name}\``,
    ].join('\n'),
  );

  return out.join('\n\n') + '\n';
}

function table(header: string[], rows: string[][]): string {
  const cells = rows.map((r) => r.map((c) => c.replace(/\|/g, '\\|')));
  const widths = header.map((h, i) => Math.max(3, h.length, ...cells.map((r) => r[i].length)));
  const line = (r: string[]) => `| ${r.map((c, i) => c.padEnd(widths[i])).join(' | ')} |`;
  return [line(header), line(widths.map((w) => '-'.repeat(w))), ...cells.map(line)].join('\n');
}

const KIND_LABEL: Record<RewriteKind, string> = {
  'cross-project': 'into another moved project',
  'base-url': 'through the source `baseUrl`',
  nrwl: '`@nrwl/*` to `@nx/*`',
  'node-modules': 'into the root `node_modules`',
  resource: 'Angular template or style URL into another moved project',
  'sass-load-path': 'through the source Sass load paths',
};

/** Compares string tuples element by element (0 on ties, for a deterministic sort). */
function byKeys(a: string[], b: string[]): number {
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  }
  return 0;
}

/** The "## Imports" section: rewritten imports by kind, then what was left as it was. */
function importsBlock(r: ImportRewriteResult): string {
  const parts: string[] = [];
  const files = new Set(r.rewritten.map((w) => w.file));
  parts.push(
    r.rewritten.length === 0
      ? 'No imports needed rewriting.'
      : `Rewrote ${r.rewritten.length} import${r.rewritten.length > 1 ? 's' : ''} in ` +
          `${files.size} copied file${files.size > 1 ? 's' : ''} (the source was not changed):`,
  );
  if (r.rewritten.length > 0) {
    parts.push(
      table(
        ['File', 'Kind', 'Before', 'After'],
        [...r.rewritten]
          .sort((a, b) => byKeys([a.file, a.before, a.kind], [b.file, b.before, b.kind]))
          .map((w) => [code(w.file), KIND_LABEL[w.kind], code(w.before), code(w.after)]),
      ),
    );
  }
  if (r.deepImports.length > 0) {
    parts.push(
      "These imports reach below another project's entry and now use a relative path; export " +
        'what they need from the library entry and import it through its alias:\n\n' +
        list(
          [...r.deepImports]
            .sort((a, b) => byKeys([a.file, a.spec], [b.file, b.spec]))
            .map((x) => `${code(x.file)}: ${code(x.spec)}`),
          'None.',
        ),
    );
  }
  if (r.unresolved.length > 0) {
    parts.push(
      'Left as they were (fix them by hand):\n\n' +
        list(
          [...r.unresolved]
            .sort((a, b) => byKeys([a.file, a.spec, a.why], [b.file, b.spec, b.why]))
            .map((x) => `${code(x.file)}: ${code(x.spec)} (${x.why})`),
          'None.',
        ),
    );
  }
  if (r.resolvedEarlier && r.resolvedEarlier.length > 0) {
    parts.push(
      'Resolved in earlier entries of this `--config` batch (imports into projects this entry ' +
        'brought in; rolling this entry back restores them):\n\n' +
        table(
          ['File', 'Before', 'After'],
          [...r.resolvedEarlier]
            .sort((a, b) => byKeys([a.file, a.before], [b.file, b.before]))
            .map((w) => [code(w.file), code(w.before), code(w.after)]),
        ),
    );
  }
  if (r.missingPackages.length > 0) {
    parts.push(
      `The rewritten imports use ${r.missingPackages.map(code).join(', ')}, which the workspace ` +
        "does not declare; add them at the workspace's Nx version (`npm i -D <package>@<nx version>`).",
    );
  }
  return parts.join('\n\n');
}

function ionicBlock(i: IonicReport): string {
  const codes = (xs: string[]) => xs.map(code).join(', ');
  const lines = [`### ${code(i.project)}`, ''];
  if (i.ionic) {
    lines.push(
      `- Ionic: ${code(i.ionic)}${
        majorOf(i.ionic) === 6 ? ' (Ionic 6: works with Angular 15; plan the move to 7)' : ''
      }`,
    );
  }
  if (i.capacitor) {
    lines.push(
      `- Capacitor: ${code(i.capacitor)}${
        majorOf(i.capacitor) !== (i.workspaceCapacitor ?? 5)
          ? ` (the workspace generates Capacitor ${
              i.workspaceCapacitor ?? 5
            } apps; this app keeps its version)`
          : ''
      }`,
    );
  }
  lines.push(
    `- Native packages (in ${code(i.packagePath)}): ${
      i.nativePackages.length > 0 ? codes(i.nativePackages) : 'none'
    }`,
  );
  if (i.alsoAtRoot.length > 0) {
    lines.push(
      `- Also in the root package.json (the code imports them, so the web build needs them): ${codes(
        i.alsoAtRoot,
      )}`,
    );
  }
  if (i.otherApps.length > 0) {
    lines.push(
      `- Left to the other Ionic apps (this app does not import them): ${codes(i.otherApps)}`,
    );
  }
  if (i.webDir?.manual === 'not-set') {
    lines.push(
      `- \`webDir\` is not set in ${code(i.webDir.file)} (Capacitor then uses \`www\`): add ` +
        `\`webDir: '${i.webDir.to}'\``,
    );
  } else if (i.webDir?.manual) {
    lines.push(
      `- \`webDir\` in ${code(i.webDir.file)}: set it to ${code(i.webDir.to)} by hand ` +
        '(it is not a plain string)',
    );
  } else if (i.webDir) {
    lines.push(
      `- \`webDir\` in ${code(i.webDir.file)}: ${code(i.webDir.from ?? '(unset)')} → ${code(
        i.webDir.to,
      )}`,
    );
  }
  if (i.outputPathMoved) {
    lines.push(`- Build output moved from ${code(i.outputPathMoved)} to the release output`);
  }
  lines.push(
    `- Native platforms copied: ${
      i.platforms.length > 0
        ? i.platforms.join(', ')
        : `none (add them with \`npx nx run ${i.project}:cap-add --platform=android\`)`
    }`,
  );
  if (i.cordovaPlugins.length > 0) {
    lines.push(
      `- Cordova plugins (check each one works with Capacitor): ${codes(i.cordovaPlugins)}`,
    );
  }
  if (i.droppedTargets.length > 0) lines.push(`- Targets dropped: ${codes(i.droppedTargets)}`);
  return lines.join('\n');
}
