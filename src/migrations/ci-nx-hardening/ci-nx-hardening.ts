import { logger, Tree } from '@nx/devkit';

/**
 * v1.13.0 (NX-114): Nx before 22.7.10 has advisories that matter on CI agents (daemon sockets
 * readable by other local users; command injection through git refs given to `nx affected`).
 * CI files pstack generated (their first line names nx-polystack) get `NX_DAEMON=false`, and the
 * generated Jenkinsfile resolves its base to a commit SHA before Nx sees it. Other CI files, and
 * generated ones whose affected step was edited, are reported, not changed.
 */

const GENERATED = /^(#|\/\/) Generated by nx-polystack/;
const CI_YML = '.github/workflows/ci.yml';
const JENKINSFILE = 'Jenkinsfile';

/** The affected step `pstack infra` generated before 1.13.0 (any targets). */
const OLD_JENKINS_AFFECTED =
  /^(\s*)sh 'npx nx affected (.*?) --base="\$\{NX_BASE\}" --head=HEAD'\s*$/;

export interface HardenResult {
  text: string;
  /** What was added, for the log. */
  done: string[];
  /** What could not be done automatically, for the log. */
  manual: string[];
}

/** ci.yml: `NX_DAEMON: 'false'` in the `main` job's env. */
export function hardenGithubCi(text: string): HardenResult {
  const res: HardenResult = { text, done: [], manual: [] };
  if (/\bNX_DAEMON\b/.test(text)) return res;
  const lines = text.split('\n');
  const main = lines.findIndex((l) => /^ {2}main:\s*$/.test(l));
  const end = (() => {
    for (let i = main + 1; i < lines.length; i++) if (/^ {0,2}\S/.test(lines[i])) return i;
    return lines.length;
  })();
  if (main < 0) {
    res.manual.push(`${CI_YML}: no "main" job; add NX_DAEMON: 'false' to the job env by hand`);
    return res;
  }
  const env = lines.findIndex((l, i) => i > main && i < end && /^ {4}env:\s*$/.test(l));
  const entry = "      NX_DAEMON: 'false'";
  if (env >= 0) {
    lines.splice(env + 1, 0, entry);
  } else {
    const runsOn = lines.findIndex((l, i) => i > main && i < end && /^ {4}runs-on:/.test(l));
    const at = runsOn >= 0 ? runsOn + 1 : main + 1;
    lines.splice(at, 0, '    env:', entry);
  }
  res.text = lines.join('\n');
  res.done.push(`${CI_YML}: NX_DAEMON=false`);
  return res;
}

/** Jenkinsfile: `NX_DAEMON = 'false'` in environment, and the affected step on commit SHAs. */
export function hardenJenkinsfile(text: string): HardenResult {
  const res: HardenResult = { text, done: [], manual: [] };
  const lines = text.split('\n');
  if (!/\bNX_DAEMON\b/.test(text)) {
    const env = lines.findIndex((l) => /^\s*environment\s*\{\s*$/.test(l));
    const indent = env >= 0 ? /^\s*/.exec(lines[env])?.[0] ?? '' : '';
    const close =
      env >= 0 ? lines.findIndex((l, i) => i > env && l.replace(/\s+$/, '') === `${indent}}`) : -1;
    if (close >= 0) {
      lines.splice(close, 0, `${indent}  NX_DAEMON = 'false'`);
      res.done.push(`${JENKINSFILE}: NX_DAEMON=false`);
    } else {
      res.manual.push(`${JENKINSFILE}: no environment block; set NX_DAEMON = 'false' by hand`);
    }
  }
  if (!/BASE_SHA=\$\(git rev-parse/.test(text)) {
    const at = lines.findIndex((l) => OLD_JENKINS_AFFECTED.test(l));
    if (at >= 0) {
      const [, indent, args] = OLD_JENKINS_AFFECTED.exec(lines[at]) ?? [];
      lines[at] =
        `${indent}sh 'BASE_SHA=$(git rev-parse --verify "\${NX_BASE}^{commit}") && ` +
        `npx nx affected ${args} --base="$BASE_SHA" --head="$(git rev-parse --verify HEAD)"'`;
      res.done.push(`${JENKINSFILE}: nx affected runs on commit SHAs`);
    } else if (/nx affected\b/.test(text)) {
      res.manual.push(
        `${JENKINSFILE}: the nx affected step was edited; resolve --base/--head to commit SHAs ` +
          '(git rev-parse --verify "<ref>^{commit}") by hand',
      );
    }
  }
  res.text = lines.join('\n');
  return res;
}

export default async function ciNxHardening(tree: Tree): Promise<void> {
  const say = (s: string) => logger.info(`ci-nx-hardening: ${s}`);
  for (const [file, harden] of [
    [CI_YML, hardenGithubCi],
    [JENKINSFILE, hardenJenkinsfile],
  ] as const) {
    const text = tree.read(file, 'utf8');
    if (text === null) continue;
    if (!GENERATED.test(text)) {
      if (!/\bNX_DAEMON\b/.test(text) && /nx affected\b/.test(text)) {
        say(
          `${file} was not generated by pstack and is left as it is; for Nx before 22.7.10 set ` +
            'NX_DAEMON=false and pass commit SHAs to nx affected (see SECURITY.md).',
        );
      }
      continue;
    }
    const res = harden(text);
    if (res.text !== text) tree.write(file, res.text);
    for (const d of res.done) say(d);
    for (const m of res.manual) say(m);
  }
}
