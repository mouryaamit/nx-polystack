import { logger, Tree } from '@nx/devkit';

import { affectedWithCiConfiguration, karmaCiChange } from '../../lib/utils/karma-ci';
import { scanProjects } from '../../lib/utils/project-json-files';

/**
 * v1.13.1 (NX-115): Karma watches by default, so `nx run-many -t test` and CI hung on Karma test
 * targets (apps `pstack migrate` brought from the Angular CLI keep Karma).
 * - Karma test targets get a `ci` configuration (watch off, ChromeHeadless);
 * - the `nx affected` step of CI files pstack generated gets `-c ci` (targets without a `ci`
 *   configuration run their default one). Other CI files are reported when they use Karma.
 */

const GENERATED = /^(#|\/\/) Generated by nx-polystack/;
const CI_FILES = ['.github/workflows/ci.yml', 'Jenkinsfile'];

export default async function karmaCi(tree: Tree): Promise<void> {
  const say = (s: string) => logger.info(`karma-ci: ${s}`);
  const added: string[] = [];
  const comments: string[] = [];
  let karma = false;
  for (const p of scanProjects(tree)) {
    const change = karmaCiChange(tree, p.root);
    if (change !== 'none') karma = true;
    if (change === 'added') added.push(p.name);
    if (change === 'comments') comments.push(`${p.root}/project.json`);
  }
  if (added.length > 0) {
    say(
      `Karma test targets of ${added.join(
        ', ',
      )} have a "ci" configuration (one run, ChromeHeadless).`,
    );
  }
  if (comments.length > 0) {
    say(
      `${comments.join(', ')} have comments and were left as they are; add ` +
        '"ci": { "watch": false, "browsers": "ChromeHeadless" } to the Karma test configurations by hand.',
    );
  }
  for (const file of CI_FILES) {
    const text = tree.read(file, 'utf8');
    if (text === null) continue;
    if (!GENERATED.test(text)) {
      if (
        karma &&
        /nx (affected|run-many)\b[^\n]*\btest\b/.test(text) &&
        !/\s(-c|--configuration)[ =]ci\b/.test(text)
      ) {
        say(
          `${file} was not generated by pstack: add -c ci to its nx test step so Karma runs once.`,
        );
      }
      continue;
    }
    const out = text.split('\n').map(affectedWithCiConfiguration).join('\n');
    if (out !== text) {
      tree.write(file, out);
      say(`${file}: nx affected runs with -c ci.`);
    }
  }
}
