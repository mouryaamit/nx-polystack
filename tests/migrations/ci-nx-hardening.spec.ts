import { execFileSync } from 'child_process';

import { logger } from '@nx/devkit';
import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';

import { setExifMode } from '../../src/lib/utils/exif-checks';
import ciNxHardening, {
  hardenGithubCi,
  hardenJenkinsfile,
} from '../../src/migrations/ci-nx-hardening/ci-nx-hardening';

/** The CI files `pstack infra` generated before 1.13.0 (the parts the migration reads). */
const OLD_CI_YML = `# Generated by nx-polystack (pstack infra). Lint, test and build what changed, then check for
# new project dependency cycles.
name: CI

jobs:
  main:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v5
      - run: npx nx affected -t lint typecheck test build --parallel=3
      - run: npm run check:cycles
`;

const OLD_JENKINSFILE = `// Generated by nx-polystack (pstack infra).
pipeline {
  agent any

  environment {
    BASE_BRANCH = "\${env.CHANGE_TARGET ?: 'main'}"
    NX_BASE = "\${env.CHANGE_TARGET ? 'origin/' + env.CHANGE_TARGET : 'origin/main'}"
  }

  stages {
    stage('Lint, test, build (affected)') {
      steps {
        sh 'npx nx affected -t lint typecheck test build --parallel=3 --base="\${NX_BASE}" --head=HEAD'
        sh 'npm run assets:check-exif'
      }
    }
  }
}
`;

describe('ci-nx-hardening migration (NX-114)', () => {
  let info: string[];
  beforeEach(() => {
    info = [];
    jest.spyOn(logger, 'info').mockImplementation((m) => void info.push(String(m)));
  });
  afterEach(() => jest.restoreAllMocks());

  it('ci.yml: NX_DAEMON in the main job env, right after runs-on', () => {
    const r = hardenGithubCi(OLD_CI_YML);
    expect(r.text).toContain(
      "  main:\n    runs-on: ubuntu-latest\n    env:\n      NX_DAEMON: 'false'\n    steps:",
    );
    expect(r.done).toEqual(['.github/workflows/ci.yml: NX_DAEMON=false']);
    expect(hardenGithubCi(r.text).text).toBe(r.text);
  });

  it('ci.yml: joins an existing job env', () => {
    const yml = OLD_CI_YML.replace(
      '    runs-on: ubuntu-latest\n',
      '    runs-on: ubuntu-latest\n    env:\n      FOO: bar\n',
    );
    expect(hardenGithubCi(yml).text).toContain(
      "    env:\n      NX_DAEMON: 'false'\n      FOO: bar\n",
    );
  });

  it('Jenkinsfile: NX_DAEMON in environment, affected on commit SHAs, other steps kept', () => {
    const r = hardenJenkinsfile(OLD_JENKINSFILE);
    expect(r.text).toContain('    NX_BASE = "${env.CHANGE_TARGET');
    expect(r.text).toContain("'origin/main'}\"\n    NX_DAEMON = 'false'\n  }");
    expect(r.text).toContain(
      `        sh 'BASE_SHA=$(git rev-parse --verify "\${NX_BASE}^{commit}") && npx nx affected -t lint typecheck test build --parallel=3 --base="$BASE_SHA" --head="$(git rev-parse --verify HEAD)"'`,
    );
    expect(r.text).toContain("        sh 'npm run assets:check-exif'");
    expect(r.done).toHaveLength(2);
    expect(hardenJenkinsfile(r.text).text).toBe(r.text);
  });

  it('Jenkinsfile with an edited affected step: NX_DAEMON added, the step reported', () => {
    const edited = OLD_JENKINSFILE.replace('--head=HEAD', '--head=HEAD --verbose');
    const r = hardenJenkinsfile(edited);
    expect(r.text).toContain("NX_DAEMON = 'false'");
    expect(r.text).toContain('--head=HEAD --verbose');
    expect(r.manual[0]).toContain('the nx affected step was edited');
  });

  it('touches only generated files; reports a foreign CI file', async () => {
    const tree = createTreeWithEmptyWorkspace();
    tree.write('.github/workflows/ci.yml', OLD_CI_YML);
    tree.write('Jenkinsfile', OLD_JENKINSFILE.replace('// Generated by nx-polystack', '// Ours'));
    await ciNxHardening(tree);
    expect(tree.read('.github/workflows/ci.yml', 'utf8')).toContain("NX_DAEMON: 'false'");
    expect(tree.read('Jenkinsfile', 'utf8')).not.toContain('NX_DAEMON');
    expect(info.join('\n')).toContain('Jenkinsfile was not generated by pstack');
    const once = tree.read('.github/workflows/ci.yml', 'utf8');
    await ciNxHardening(tree);
    expect(tree.read('.github/workflows/ci.yml', 'utf8')).toBe(once);
  });

  it('the Jenkins step is valid shell and fails when the base is not a commit', () => {
    const line = hardenJenkinsfile(OLD_JENKINSFILE)
      .text.split('\n')
      .find((l) => l.includes('BASE_SHA='));
    const cmd = /sh '(.*)'/.exec(line ?? '')?.[1] ?? '';
    expect(() => execFileSync('sh', ['-n', '-c', cmd])).not.toThrow();
    // With a base that is no commit, rev-parse fails and nx is never run.
    const probe = cmd.replace('npx nx affected', 'echo RAN');
    expect(() =>
      execFileSync('sh', ['-c', probe], {
        env: { ...process.env, NX_BASE: 'origin/$(touch /tmp/pwned)' },
        cwd: process.cwd(),
        stdio: 'pipe',
      }),
    ).toThrow();
  });

  it('pstack infra --exif still finds the hardened affected step', () => {
    const tree = createTreeWithEmptyWorkspace();
    const hardened = hardenJenkinsfile(OLD_JENKINSFILE).text.replace(
      "        sh 'npm run assets:check-exif'\n",
      '',
    );
    tree.write('Jenkinsfile', hardened);
    expect(setExifMode(tree, 'check').ci.changed).toEqual(['Jenkinsfile']);
    const lines = (tree.read('Jenkinsfile', 'utf8') ?? '').split('\n');
    const at = lines.findIndex((l) => l.includes('BASE_SHA='));
    expect(lines[at + 1]).toBe("        sh 'npm run assets:check-exif'");
  });
});
