import { logger, Tree } from '@nx/devkit';
import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';

import {
  affectedWithCiConfiguration,
  isKarmaTarget,
  modernizeKarmaConfigs,
  modernKarmaConfig,
  withKarmaCi,
} from '../../src/lib/utils/karma-ci';
import karmaCi from '../../src/migrations/karma-ci/karma-ci';

const KARMA = '@angular-devkit/build-angular:karma';
const CI = { watch: false, browsers: 'ChromeHeadless' };

const GITHUB_STEP = '      - run: npx nx affected -t lint typecheck test build --parallel=3';
const JENKINS_STEP =
  `        sh 'BASE_SHA=$(git rev-parse --verify "\${NX_BASE}^{commit}") && ` +
  `npx nx affected -t lint typecheck test build --parallel=3 --base="$BASE_SHA" ` +
  `--head="$(git rev-parse --verify HEAD)"'`;

describe('karma ci configuration (NX-115)', () => {
  it('isKarmaTarget: Angular Karma builders, as executor or builder', () => {
    expect(isKarmaTarget({ executor: KARMA })).toBe(true);
    expect(isKarmaTarget({ builder: '@angular/build:karma' })).toBe(true);
    expect(isKarmaTarget({ executor: '@nx/jest:jest' })).toBe(false);
    expect(isKarmaTarget(undefined)).toBe(false);
  });

  it('withKarmaCi adds ci next to the other configurations and keeps an existing one', () => {
    const t = { executor: KARMA, options: { main: 'src/test.ts' }, configurations: { x: {} } };
    expect(withKarmaCi(t)).toEqual({ ...t, configurations: { x: {}, ci: CI } });
    const own = { executor: KARMA, configurations: { ci: { browsers: 'FirefoxHeadless' } } };
    expect(withKarmaCi(own)).toBe(own);
    const jest = { executor: '@nx/jest:jest' };
    expect(withKarmaCi(jest)).toBe(jest);
  });

  it('affectedWithCiConfiguration: -c ci after the targets, once', () => {
    expect(affectedWithCiConfiguration(GITHUB_STEP)).toBe(
      '      - run: npx nx affected -t lint typecheck test build -c ci --parallel=3',
    );
    const j = affectedWithCiConfiguration(JENKINS_STEP);
    expect(j).toContain('npx nx affected -t lint typecheck test build -c ci --parallel=3 --base=');
    expect(affectedWithCiConfiguration(j)).toBe(j);
    // Its own configuration is kept; other lines are not touched.
    const own = '      - run: npx nx affected -t test --configuration=production';
    expect(affectedWithCiConfiguration(own)).toBe(own);
    expect(affectedWithCiConfiguration('      - run: npm run check:cycles')).toBe(
      '      - run: npm run check:cycles',
    );
  });
});

describe('Angular CLI 1.x Karma configs (NX-117)', () => {
  const OLD = `module.exports = function (config) {
  config.set({
    frameworks: ['jasmine', '@angular/cli'],
    plugins: [
      require('karma-jasmine'),
      require('@angular/cli/plugins/karma')
    ],
    angularCli: {
      environment: 'dev'
    },
    browsers: ['Chrome'],
  });
};
`;

  it('moves the framework and plugin to @angular-devkit/build-angular and drops angularCli', () => {
    expect(modernKarmaConfig(OLD)).toBe(`module.exports = function (config) {
  config.set({
    frameworks: ['jasmine', '@angular-devkit/build-angular'],
    plugins: [
      require('karma-jasmine'),
      require('@angular-devkit/build-angular/plugins/karma')
    ],
    browsers: ['Chrome'],
  });
};
`);
    const current = modernKarmaConfig(OLD);
    expect(modernKarmaConfig(current)).toBe(current);
  });

  it("rewrites the karmaConfig files of a project's Karma targets only", () => {
    const tree = createTreeWithEmptyWorkspace();
    tree.write('apps/shop/karma.conf.js', OLD);
    tree.write('apps/shop/other.karma.js', OLD);
    const changed = modernizeKarmaConfigs(tree, {
      targets: {
        test: { executor: KARMA, options: { karmaConfig: 'apps/shop/karma.conf.js' } },
        build: { executor: '@angular-devkit/build-angular:browser' },
      },
    });
    expect(changed).toEqual(['apps/shop/karma.conf.js']);
    expect(tree.read('apps/shop/karma.conf.js', 'utf8')).not.toContain('@angular/cli');
    expect(tree.read('apps/shop/other.karma.js', 'utf8')).toBe(OLD);
  });
});

describe('karma-ci migration (NX-115)', () => {
  let info: string[];
  let tree: Tree;
  const project = (root: string, targets: Record<string, unknown>) =>
    tree.write(
      `${root}/project.json`,
      JSON.stringify({ name: root.split('/').pop(), targets }, null, 2),
    );
  const json = (f: string) => JSON.parse(tree.read(f, 'utf8') ?? '');

  beforeEach(() => {
    info = [];
    jest.spyOn(logger, 'info').mockImplementation((m) => void info.push(String(m)));
    tree = createTreeWithEmptyWorkspace();
  });
  afterEach(() => jest.restoreAllMocks());

  it('Karma test targets get ci; generated CI gets -c ci; a second run changes nothing', async () => {
    project('apps/std', { test: { executor: KARMA, options: { main: 'apps/std/src/test.ts' } } });
    project('apps/web', { test: { executor: '@nx/jest:jest' } });
    tree.write(
      '.github/workflows/ci.yml',
      `# Generated by nx-polystack (pstack infra).\njobs:\n  main:\n    steps:\n${GITHUB_STEP}\n`,
    );
    tree.write('Jenkinsfile', `// Generated by nx-polystack (pstack infra).\n${JENKINS_STEP}\n`);

    await karmaCi(tree);
    expect(json('apps/std/project.json').targets.test.configurations).toEqual({ ci: CI });
    expect(json('apps/web/project.json').targets.test.configurations).toBeUndefined();
    expect(tree.read('.github/workflows/ci.yml', 'utf8')).toContain(
      'npx nx affected -t lint typecheck test build -c ci --parallel=3',
    );
    expect(tree.read('Jenkinsfile', 'utf8')).toContain(
      'npx nx affected -t lint typecheck test build -c ci --parallel=3',
    );
    expect(info.join('\n')).toContain('Karma test targets of std have a "ci" configuration');

    const snapshot = ['apps/std/project.json', '.github/workflows/ci.yml', 'Jenkinsfile'].map((f) =>
      tree.read(f, 'utf8'),
    );
    await karmaCi(tree);
    expect(
      ['apps/std/project.json', '.github/workflows/ci.yml', 'Jenkinsfile'].map((f) =>
        tree.read(f, 'utf8'),
      ),
    ).toEqual(snapshot);
  });

  it('CI files pstack did not generate are reported when a Karma target exists, not edited', async () => {
    project('apps/std', { test: { executor: KARMA } });
    const own = `name: CI\njobs:\n  main:\n    steps:\n      - run: npx nx affected -t test\n`;
    tree.write('.github/workflows/ci.yml', own);
    await karmaCi(tree);
    expect(tree.read('.github/workflows/ci.yml', 'utf8')).toBe(own);
    expect(info.join('\n')).toContain(
      '.github/workflows/ci.yml was not generated by pstack: add -c ci',
    );
  });

  it('project.json with comments is listed, not rewritten', async () => {
    const text = `{\n  // a comment\n  "name": "std",\n  "targets": { "test": { "executor": "${KARMA}" } }\n}\n`;
    tree.write('apps/std/project.json', text);
    await karmaCi(tree);
    expect(tree.read('apps/std/project.json', 'utf8')).toBe(text);
    expect(info.join('\n')).toContain('apps/std/project.json have comments');
  });
});
